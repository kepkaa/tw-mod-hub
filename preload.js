const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('modhub', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (patch) => ipcRenderer.invoke('settings:save', patch),
  twitchLogin: () => ipcRenderer.invoke('twitch:login'),
  twitchLogout: () => ipcRenderer.invoke('twitch:logout'),
  followed: () => ipcRenderer.invoke('twitch:followed'),
  following: () => ipcRenderer.invoke('twitch:following'),
  playerPort: () => ipcRenderer.invoke('player:port'),
  registerHotkeys: (macros) => ipcRenderer.invoke('hotkeys:register', macros),
  exportAhk: (macros) => ipcRenderer.invoke('ahk:export', macros),
  openExternal: (url) => ipcRenderer.invoke('open:external', url),
  dbLog: (a) => ipcRenderer.invoke('db:log', a),
  dbHistory: (o) => ipcRenderer.invoke('db:history', o),
  dbNick: (n) => ipcRenderer.invoke('db:nick', n),
  dbNoteSet: (n, note) => ipcRenderer.invoke('db:noteSet', n, note),
  dbStats: () => ipcRenderer.invoke('db:stats'),
  dbFavs: () => ipcRenderer.invoke('db:favs'),
  dbFavToggle: (c) => ipcRenderer.invoke('db:favToggle', c),
  dbWatch: (c) => ipcRenderer.invoke('db:watch', c),
  dbRecent: () => ipcRenderer.invoke('db:recent'),
  dbExportCsv: () => ipcRenderer.invoke('db:exportCsv'),
  resetSettings: () => ipcRenderer.invoke('settings:reset'),
  openDataDir: () => ipcRenderer.invoke('app:openData'),
  appStatus: () => ipcRenderer.invoke('app:status'),
  logError: (m) => ipcRenderer.invoke('app:logError', m),
  onHotkey: (cb) => ipcRenderer.on('hotkey', (e, id) => cb(id)),
  onUpdate: (cb) => ipcRenderer.on('update', (e, d) => cb(d)),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  chatAuth: () => ipcRenderer.invoke('chat:auth'),
  checkMod: (ch) => ipcRenderer.invoke('twitch:checkMod', ch),
  chatCommand: (ch, text) => ipcRenderer.invoke('chat:command', ch, text),
  badges: (ch) => ipcRenderer.invoke('twitch:badges', ch),
  points: (ch) => ipcRenderer.invoke('twitch:points', ch),
  pointsWatch: (ch) => ipcRenderer.invoke('points:watch', ch),
  pointsStop: () => ipcRenderer.invoke('points:stop'),
  onPoints: (cb) => ipcRenderer.on('points', (e, d) => cb(d)),
  bcState: (a) => ipcRenderer.invoke('bc:state', a),
  pollCreate: (a) => ipcRenderer.invoke('poll:create', a),
  pollEnd: (a) => ipcRenderer.invoke('poll:end', a),
  predCreate: (a) => ipcRenderer.invoke('pred:create', a),
  predSet: (a) => ipcRenderer.invoke('pred:set', a),
  adminState: () => ipcRenderer.invoke('admin:state'),
  adminSetup: (pw) => ipcRenderer.invoke('admin:setup', pw),
  adminUnlock: (pw) => ipcRenderer.invoke('admin:unlock', pw),
  adminLock: () => ipcRenderer.invoke('admin:lock'),
  adminSaveCfg: (cfg) => ipcRenderer.invoke('admin:saveCfg', cfg),
  adminExportConfig: () => ipcRenderer.invoke('admin:exportConfig'),
  adminForceFetch: () => ipcRenderer.invoke('admin:forceFetch'),
  onRemote: (cb) => ipcRenderer.on('remote', (e, d) => cb(d)),
  onAuthExpired: (cb) => ipcRenderer.on('auth-expired', () => cb()),
});